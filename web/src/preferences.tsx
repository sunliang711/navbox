type PreferencesContextValue = {
  theme: ThemeMode;
  language: LanguageMode;
  layout: LayoutMode;
  setTheme: (theme: ThemeMode) => void;
  setLanguage: (language: LanguageMode) => void;
  setLayout: (layout: LayoutMode) => void;
  t: (key: TranslationKey, values?: Record<string, string | number>) => string;
};

const PreferencesContext = createContext<PreferencesContextValue | null>(null);

export function PreferencesProvider({ children }: { children: ReactNode }) {
  const [theme, setThemeState] = useState<ThemeMode>(() => loadTheme());
  const [language, setLanguageState] = useState<LanguageMode>(() => loadLanguage());
  const [layout, setLayoutState] = useState<LayoutMode>(() => loadLayout());

  useEffect(() => {
    document.documentElement.dataset.layout = layout;
    try {
      window.localStorage.setItem(layoutKey, layout);
    } catch {
      // localStorage 不可用时，首页和后台仍共享当前会话中的布局。
    }
  }, [layout]);

  useEffect(() => {
    function syncLayout(event: StorageEvent) {
      if (event.key === layoutKey && event.storageArea === window.localStorage) {
        setLayoutState(event.newValue === 'directory' ? 'directory' : 'workbench');
      }
    }
    window.addEventListener('storage', syncLayout);
    return () => window.removeEventListener('storage', syncLayout);
  }, []);

  useEffect(() => {
    document.documentElement.dataset.theme = theme;
    document.documentElement.style.colorScheme = theme;
    try {
      window.localStorage.setItem(themeKey, theme);
    } catch {
      // localStorage 不可用时只保留当前会话状态。
    }
  }, [theme]);

  useEffect(() => {
    document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
    try {
      window.localStorage.setItem(languageKey, language);
    } catch {
      // localStorage 不可用时只保留当前会话状态。
    }
  }, [language]);

  // 布局切换不改变翻译函数引用，避免触发页面的数据加载与筛选初始化。
  const translate = useMemo(() => {
    const dictionary = language === 'zh' ? zh : en;
    return (key: TranslationKey, values?: Record<string, string | number>) => interpolate(dictionary[key], values);
  }, [language]);

  const value = useMemo<PreferencesContextValue>(() => {
    return {
      theme,
      language,
      layout,
      setTheme: setThemeState,
      setLanguage: setLanguageState,
      setLayout: setLayoutState,
      t: translate
    };
  }, [language, layout, theme, translate]);

  return <PreferencesContext.Provider value={value}>{children}</PreferencesContext.Provider>;
}

export function usePreferences(): PreferencesContextValue {
  const context = useContext(PreferencesContext);
  if (!context) {
    throw new Error('usePreferences must be used within PreferencesProvider');
  }
  return context;
}

export function PreferenceControls() {
  const { language, layout, setLanguage, setLayout, setTheme, t, theme } = usePreferences();
  const nextTheme = theme === 'light' ? 'dark' : 'light';
  const nextThemeLabel = nextTheme === 'dark' ? t('darkMode') : t('lightMode');
  const nextLayout = layout === 'workbench' ? 'directory' : 'workbench';
  const nextLayoutLabel = nextLayout === 'directory' ? t('directoryLayout') : t('workbenchLayout');

  return (
    <div className="preference-controls">
      <div className="preference-group" role="group" aria-label={t('layoutStyle')}>
        <button
          className="preference-button layout-preference-button"
          type="button"
          onClick={() => setLayout(nextLayout)}
          title={nextLayoutLabel}
          aria-label={nextLayoutLabel}
        >
          {nextLayout === 'directory' ? <List size={15} aria-hidden="true" /> : <LayoutGrid size={15} aria-hidden="true" />}
          <span>{nextLayoutLabel}</span>
        </button>
      </div>
      <div className="preference-group" role="group" aria-label={`${t('lightMode')} / ${t('darkMode')}`}>
        <button
          className="preference-button theme-preference-button"
          type="button"
          onClick={() => setTheme(nextTheme)}
          title={nextThemeLabel}
          aria-label={nextThemeLabel}
        >
          {theme === 'light' ? <Moon size={15} aria-hidden="true" /> : <Sun size={15} aria-hidden="true" />}
          <span>{nextThemeLabel}</span>
        </button>
      </div>
      <div className="preference-group" role="group" aria-label={t('language')}>
        <button
          className={language === 'zh' ? 'preference-button active' : 'preference-button'}
          type="button"
          onClick={() => setLanguage(language === 'zh' ? 'en' : 'zh')}
          title={t('language')}
        >
          <Languages size={15} aria-hidden="true" />
          <span>{language === 'zh' ? '中文' : 'EN'}</span>
        </button>
      </div>
    </div>
  );
}

function interpolate(text: string, values: Record<string, string | number> = {}): string {
  return Object.entries(values).reduce((result, [key, value]) => {
    return result.split(`{{${key}}}`).join(String(value));
  }, text);
}

function loadTheme(): ThemeMode {
  try {
    const value = window.localStorage.getItem(themeKey);
    return value === 'light' ? 'light' : 'dark';
  } catch {
    return 'dark';
  }
}

function loadLanguage(): LanguageMode {
  try {
    const value = window.localStorage.getItem(languageKey);
    return value === 'en' ? 'en' : 'zh';
  } catch {
    return 'zh';
  }
}

function loadLayout(): LayoutMode {
  try {
    return window.localStorage.getItem(layoutKey) === 'directory' ? 'directory' : 'workbench';
  } catch {
    return 'workbench';
  }
}
